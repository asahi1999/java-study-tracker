void main() {
    for (int x = 0; x < 7; x++) {
        System.out.print("#");
    }
    System.out.println();

    System.out.print("#");
    int step = 0;
    while (step < 5) {
        System.out.print(".");
        step++;
    }
    System.out.println("#");

    for (int x = 0; x < 7; x++) {
        System.out.print("#");
    }
    System.out.println();
}
