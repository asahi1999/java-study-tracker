void main() {
    for (int x = 0; x < 11; x++) {
        if (x == 2 || x == 5 || x == 8) {
            System.out.print("*");
        } else {
            System.out.print("#");
        }
    }
    System.out.println();
    System.out.println("#.........#");
    System.out.println("#....@....#");
    System.out.println("###########");
}
